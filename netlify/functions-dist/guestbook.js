function sanitizePlainText(value, maxLength) {
  if (typeof value !== "string") return "";
  return value.normalize("NFKC").replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g, "").replace(/[<>]/g, "").replace(/\r\n?/g, "\n").trim().slice(0, maxLength);
}

